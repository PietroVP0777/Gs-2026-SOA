CREATE TABLE trajetos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(80) NOT NULL,
    apelido        VARCHAR(40) NOT NULL,
    horario_saida  TIME        NOT NULL,
    ativo          BOOLEAN     NOT NULL,
    criado_em      TIMESTAMP   NOT NULL
);

CREATE TABLE trajeto_linhas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trajeto_id  BIGINT  NOT NULL,
    linha_id    BIGINT  NOT NULL,
    ordem       INTEGER NOT NULL,
    CONSTRAINT fk_trajeto_linhas_trajeto FOREIGN KEY (trajeto_id) REFERENCES trajetos (id) ON DELETE CASCADE,
    CONSTRAINT fk_trajeto_linhas_linha   FOREIGN KEY (linha_id)   REFERENCES linhas (id)
);

CREATE INDEX ix_trajeto_linhas_trajeto_id ON trajeto_linhas (trajeto_id);

CREATE TABLE alertas (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trajeto_id          BIGINT        NOT NULL,
    status              VARCHAR(10)   NOT NULL,
    mensagem            VARCHAR(300)  NOT NULL,
    linha_mais_afetada  VARCHAR(80),
    criado_em           TIMESTAMP     NOT NULL,
    CONSTRAINT fk_alertas_trajeto FOREIGN KEY (trajeto_id) REFERENCES trajetos (id) ON DELETE CASCADE
);

CREATE INDEX ix_alertas_trajeto_id ON alertas (trajeto_id);
