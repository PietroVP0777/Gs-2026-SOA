CREATE TABLE linhas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(80) NOT NULL,
    tipo       VARCHAR(10) NOT NULL,
    operadora  VARCHAR(80) NOT NULL,
    cor        VARCHAR(30),
    CONSTRAINT uq_linhas_nome UNIQUE (nome)
);

CREATE TABLE relatos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    linha_id        BIGINT       NOT NULL,
    tipo            VARCHAR(30)  NOT NULL,
    nivel_lotacao   VARCHAR(20),
    minutos_atraso  INTEGER,
    descricao       VARCHAR(280),
    criado_em       TIMESTAMP    NOT NULL,
    CONSTRAINT fk_relatos_linha FOREIGN KEY (linha_id) REFERENCES linhas (id) ON DELETE CASCADE
);

CREATE INDEX ix_relatos_linha_criado_em ON relatos (linha_id, criado_em);
